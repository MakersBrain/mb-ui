import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'src/tokens.css');
const destination = resolve(root, 'src/adapters/odoo.scss');
const source = readFileSync(sourcePath, 'utf8');
const rootBlock = source.match(/:root\s*\{([\s\S]*?)\n\}/)?.[1];
if (!rootBlock) throw new Error('tokens.css has no base :root block');

const values = new Map();
for (const match of rootBlock.matchAll(/--mb-([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})\s*;/g)) {
  values.set(match[1], match[2].toLowerCase());
}

const required = [
  'clay-50', 'clay-200', 'clay-600', 'clay-700', 'clay-800',
  'sand-100', 'sand-200', 'sand-300', 'sand-400', 'sand-500',
  'sand-600', 'sand-700', 'sand-800', 'sand-900'
];
for (const name of required) {
  if (!values.has(name)) throw new Error(`tokens.css is missing --mb-${name}`);
}

const lines = [
  '// Generated from @makersbrain/ui/tokens.css by scripts/build-odoo-scss.mjs.',
  '// Do not edit this file or its checked-in Odoo projection by hand.',
  ...required.map((name) => `$mb-${name}: ${values.get(name)};`),
  '$mb-page-ground: #f7f3ee;',
  '$mb-surface: #ffffff;',
  ''
];
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(destination, 'utf8'); } catch {}
  if (current !== output) {
    console.error('src/adapters/odoo.scss is stale; run npm run build:odoo');
    process.exit(1);
  }
  console.log('Odoo SCSS projection matches tokens.css');
} else {
  writeFileSync(destination, output);
  console.log('wrote src/adapters/odoo.scss');
}
